// Generates src/ui/icons.js with only the Lucide icons the app uses.
// Usage: node scripts/build-icons.mjs <path-to-lucide-package>
// (npm pack lucide@<version> && tar -xzf lucide-*.tgz  ->  ./package)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ICONS = [
  'activity','arrow-left','arrow-right','badge-check','bell','building','calendar','check','chevron-down','chevron-right',
  'circle-alert','circle-check','clock','rotate-ccw','copy','download','ellipsis','eye','file-plus','file-text','globe',
  'inbox','info','key-round','languages','layout-dashboard','link-2','list-checks','lock','log-out','mail','menu',
  'moon','network','pencil','plus','refresh-cw','search','send','settings','share-2','shield-check','sun',
  'trash','triangle-alert','unlink','upload','user-check','user-plus','users','x'
];

const pkg = process.argv[2];
if (!pkg) { console.error('usage: node scripts/build-icons.mjs <lucide package dir>'); process.exit(1); }
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const out = {};
for (const name of ICONS) {
  const src = readFileSync(join(pkg, 'dist/esm/icons', `${name}.mjs`), 'utf8');
  const node = JSON.parse(src.slice(src.indexOf('= [') + 2, src.lastIndexOf('];') + 1)
    .replace(/(\w+):/g, '"$1":'));
  out[name] = node.map(([tag, attrs]) =>
    `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
}
writeFileSync(new URL('../src/ui/icons.js', import.meta.url), `// Generated by scripts/build-icons.mjs from lucide v${version} (ISC license). Do not edit.
export const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};
`);
console.log(`wrote ${ICONS.length} icons from lucide v${version}`);
